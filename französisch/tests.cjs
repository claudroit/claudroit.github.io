const fs = require('fs'), path = require('path');
const WORDS = require('./words-data.js');
const { checkFr, shownFr, mascFr } = new Function(fs.readFileSync(path.join(__dirname, 'check.js'), 'utf8') + ';return { checkFr, shownFr, mascFr };')();

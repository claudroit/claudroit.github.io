const assert = require('node:assert/strict');
global.EnglishStudy = require('./core.js');
const sets = require('./sets.js');
const words = require('./data.js');
const study = global.EnglishStudy;
const memory = new Map();
const storage = { getItem: key => memory.get(key) ?? null, setItem: (key, value) => memory.set(key, value) };
const old = study.freshState();
let run = study.start(old, 'first', words);
study.record(old, run, true); study.record(old, run, false);
storage.setItem(sets.legacyKey, JSON.stringify(old));
const app = sets.load(storage, words);
assert.deepEqual(app.sets[0].progress, old);
assert.equal(storage.getItem(sets.legacyKey), JSON.stringify(old));
sets.addBuiltin(app, storage, words);
assert.equal(app.sets.length, 1);
assert.deepEqual(app.sets[0].progress, old);
storage.setItem(sets.key, JSON.stringify(app));
assert.deepEqual(sets.load(storage, words), app);
const pairs = sets.importText('English\tGerman\r\nhouse\tHaus\r\ntree\tBaum\r\n');
assert.deepEqual(pairs.map(({en,de}) => [en,de]), [['house','Haus'],['tree','Baum']]);
assert.deepEqual(sets.importText('"Werte, Vorstellungen",values', ',', 'de').map(({en,de}) => [en,de]), [['values','Werte, Vorstellungen']]);
assert.throws(() => sets.importText('missing\t'));
assert.throws(() => sets.importText('a\tb\tc'));
assert.throws(() => sets.importText('"unclosed\tb'));
const set = sets.create('Test', pairs);
set.marks[pairs[0].id] = true;
run = study.start(set.progress, 'first', set.words);
study.record(set.progress, run, true);
const saved = sets.clone(set.progress);
sets.edit(set, { title: 'Renamed', description: '', words: sets.clone(pairs) });
assert.deepEqual(set.progress, saved);
const changed = sets.clone(pairs); changed[1].en = 'wood';
sets.edit(set, { title: 'Renamed', description: '', words: changed });
assert.equal(set.progress.known[pairs[0].id].k, true);
assert.equal(set.marks[pairs[0].id], true);
assert.deepEqual(set.progress.runs, {});
assert.equal(sets.payload(set).progress, undefined);
assert.deepEqual(sets.payload(set, true).progress, set.progress);
assert.throws(() => sets.validate({ title:'bad', description:'', words:[{id:'__proto__',en:'bad',de:'bad'}] }));
assert.throws(() => sets.validate({ title:'bad', description:'', words:[pairs[0],pairs[0]] }));
assert.ok(study.checkGerman({ de: 'groß, riesig' }, 'gross'));
assert.ok(study.check({ id:'custom', en:'house | home', de:'Haus' }, 'home', [{id:'custom',en:'house | home',de:'Haus'}]));
(async () => {
  const decoded = await sets.decode(await sets.encode(set, true));
  assert.deepEqual(decoded.words, set.words);
  assert.deepEqual(decoded.progress, set.progress);
  assert.deepEqual(decoded.marks, set.marks);
  const fresh = await sets.decode(await sets.encode(set));
  assert.deepEqual(fresh.progress, study.freshState());
  assert.deepEqual(fresh.marks, {});
  const full = sets.create('Excel', words);
  assert.equal((await sets.decode(await sets.encode(full))).words.length, 358);
  await assert.rejects(sets.decode('g.not-valid!'));
  console.log('PASS: legacy migration, non-overwriting starter link, set isolation, CSV/TSV, editing preservation, optional progress and full 358-word link round trip.');
})().catch(error => { console.error(error); process.exitCode = 1; });
